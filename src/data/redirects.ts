/**
 * The site's redirects, declared in one place.
 *
 * Why this is not just a text file
 * --------------------------------
 *
 * A `_redirects` file is a list of strings, and nothing checks it. Two
 * mistakes are easy to make and hard to see:
 *
 *   * A redirect whose target is the *other* spelling of the same path
 *     (`/notes/*` → `/notes`) loops forever, because Cloudflare Pages
 *     canonicalises the target right back to the source.
 *   * A redirect that points at a page which no longer exists sends the
 *     visitor to a 404.
 *
 * Neither is visible in the file itself, and neither shows up in a local
 * `astro dev` — the dev server does not read `_redirects` at all. Both only
 * appear after the site has been deployed.
 *
 * So the redirects are declared here, as data, and a build step turns them
 * into the `_redirects` file and then *verifies* the result by simulating
 * Cloudflare's routing engine against the built site. A redirect that loops
 * or that points nowhere fails the build instead of the deployment.
 */

/**
 * A single redirect rule.
 *
 * `from` is a path pattern; `to` is either a fixed path or a template that
 * refers to the parameters of `from`.
 */
export type RedirectRule = {
  /**
   * The source pattern.
   *
   * Two kinds of wildcard are available, and the difference matters:
   *
   *   * `:name` matches exactly one path segment — at least one character.
   *   * `*` matches any number of characters, *including none*.
   *
   * A rule that uses `*` therefore also matches the bare prefix, which is
   * how `/notes/*` ends up fighting with the `/notes/` page. Use `:name`
   * when a segment is required.
   */
  from: string;
  /**
   * The destination. `:name` refers to the parameter of the same name in
   * `from`; `*` refers to the splat.
   */
  to: string;
  /** The HTTP status code. Permanent redirects are the default. */
  status?: 301 | 302;
  /** Why the rule exists — written for the next person who reads it. */
  why: string;
};

/**
 * Every redirect the site serves.
 *
 * The order matters: Cloudflare Pages applies the first matching rule, so
 * the more specific rules have to come first. Static rules (a fixed path)
 * are also more efficient than dynamic ones (a path with a placeholder), so
 * they come first here too — the same order Cloudflare's own documentation
 * recommends.
 */
export const REDIRECTS: RedirectRule[] = [
  {
    /*
     * The tag index is gone — the search page lists every tag.
     */
    from: "/tags",
    to: "/search/",
    why: "the tag index is gone; the search page lists every tag",
  },
  {
    /*
     * The archives page was removed — the paginated listing replaces it.
     */
    from: "/archives",
    to: "/posts/",
    why: "the archives page was replaced by the listing",
  },
  {
    /*
     * The tag pages were removed in the redesign: the tags now live on the
     * search page, which filters across all four collections at once.
     *
     * The tag is carried over as a query parameter, so that
     * `/tags/astro` still lands on the *filtered* search results rather
     * than on the unfiltered page. The trailing-slash variant is listed
     * separately because `:tag` does not match an empty segment.
     */
    from: "/tags/:tag/",
    to: "/search/?tag=:tag",
    why: "the old tag pages are gone; keep the tag as a search filter",
  },
  {
    from: "/tags/:tag",
    to: "/search/?tag=:tag",
    why: "the old tag pages are gone; keep the tag as a search filter",
  },
  {
    /*
     * The catch-all for the old paginated tag pages. It has to come after
     * the two rules above, which are more specific.
     */
    from: "/tags/*",
    to: "/search/",
    why: "catch-all for old paginated tag pages",
  },
  {
    /*
     * Notes have no detail pages — a note is expanded in place on the
     * listing. The old per-note URLs (which used a UUID) therefore have to
     * land on the listing.
     *
     * `:id` and not `*`: a splat also matches the empty string, so `/notes/*`
     * would match `/notes/` itself and send the listing to itself. The
     * placeholder matches exactly one segment, so `/notes/` is left alone.
     */
    from: "/notes/:id",
    to: "/notes/",
    why: "notes have no detail pages; they live on the listing",
  },
];

/**
 * Renders the redirect table as the contents of a Cloudflare Pages
 * `_redirects` file.
 */
export function renderRedirectsFile(rules: RedirectRule[] = REDIRECTS): string {
  const lines = [
    "# Cloudflare Pages redirects.",
    "#",
    "# Generated from src/data/redirects.ts — do not edit this file by hand.",
    "# Run `pnpm run build` (or `node scripts/redirects.mjs --write`) to",
    "# regenerate it. The build verifies the result against a simulation of",
    "# Cloudflare's routing engine, so a redirect that loops fails the build.",
    "",
  ];

  for (const rule of rules) {
    const status = rule.status ?? 301;
    lines.push(`# ${rule.why}`);
    lines.push(`${rule.from}  ${rule.to}  ${status}`);
    lines.push("");
  }

  return lines.join("\n");
}
